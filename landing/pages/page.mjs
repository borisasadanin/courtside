/** One of the films in films.html, with its {{key.path}} text filled in. */
function film(name, t) {
  const m = filmsSrc.match(new RegExp(`<!--${name}-->([\\s\\S]*?)<!--/${name}-->`));
  return m[1].replace(/\{\{([\w.]+)\}\}/g, (_, k) => k.split(".").reduce((o, p) => o[p], t));
}

